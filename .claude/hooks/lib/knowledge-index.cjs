'use strict';

/**
 * Knowledge index: the generated view of each plane's packs (spec KNW, BR-KNW-04/05/19).
 *
 * Two planes:
 *   - framework — `.claude/knowledge-base/` (packs, `index.json`, generated `README.md` reader list)
 *   - project   — the directory named by the `**Packs directory:**` header of
 *                 `knowledge-base-reference.md` in the project-reference root (default
 *                 `docs/knowledge-base/`), holding packs and `index.json`; the reader list is the
 *                 generated block of `knowledge-base-reference.md` and lists BOTH planes.
 *
 * Pack frontmatter is the only source of truth. `buildPlane` derives the index deterministically
 * (no timestamps, packs sorted by identity, content hashes instead of modification times), so
 * generating twice gives byte-identical output and `checkPlanes` can compare stored with fresh.
 * Writes replace each file whole (temp file + rename). Delivery uses `loadForDelivery`, which never
 * writes an index: when packs changed after generation it rebuilds the plane in memory.
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const packs = require('./knowledge-pack.cjs');

const SCHEMA = 1;
const FRAMEWORK_DIR_REL = '.claude/knowledge-base';
const PROJECT_DIR_DEFAULT_REL = 'docs/knowledge-base';
const REFERENCE_FILENAME = 'knowledge-base-reference.md';
const INDEX_FILENAME = 'index.json';
const FRAMEWORK_READER_FILENAME = 'README.md';
const EXCLUDED_FILENAMES = new Set(['readme.md', 'index.md']);
const PLANE_SOFT_MAX = 60;
const BLOCK_START = '<!-- KNOWLEDGE-BASE:START — generated by /knowledge-base build; do not edit by hand -->';
const BLOCK_END = '<!-- KNOWLEDGE-BASE:END -->';
const PACKS_HEADER = /^\*\*Packs directory:\*\*\s*`?([^`\s]+)`?\s*$/m;

function toPosix(rel) {
    return rel.split(path.sep).join('/');
}

function rel(projectDir, abs) {
    return toPosix(path.relative(projectDir, abs));
}

/** Text as content: a byte-order mark and CRLF/CR line endings are checkout policy, not a change (BR-KNW-04). */
function contentText(text) {
    return String(text).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}

function hashText(text) {
    return crypto.createHash('sha256').update(contentText(text), 'utf8').digest('hex').slice(0, 16);
}

function readText(file) {
    try {
        return fs.readFileSync(file, 'utf8');
    } catch {
        return null;
    }
}

function readJson(file) {
    const text = readText(file);
    if (text === null) return null;
    try {
        return JSON.parse(text.replace(/^﻿/, ''));
    } catch {
        return null;
    }
}

/** Atomic whole-file replace (BR-KNW-04): temp file in the same directory, then rename. */
function writeFileAtomic(file, content) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const temp = `${file}.${process.pid}.${crypto.randomBytes(4).toString('hex')}.tmp`;
    try {
        fs.writeFileSync(temp, content);
        fs.renameSync(temp, file);
    } catch (error) {
        try {
            fs.unlinkSync(temp);
        } catch {
            /* never created */
        }
        throw error;
    }
}

/**
 * The project-reference root of `projectDir`. The project config loader owns the config location, the
 * `docsRoots.projectReference.path` key, its default and its containment; an unreadable config uses the
 * default. Never throws.
 */
function projectReferenceRoot(projectDir) {
    const loader = require('./project-config-loader.cjs');
    let config = {};
    try {
        config = loader.readProjectConfigAt(projectDir).config || {};
    } catch {
        config = {};
    }
    return path.join(projectDir, ...loader.getDocsRoot('projectReference', config).split('/'));
}

/** A project-relative POSIX path with no absolute prefix, drive letter or `..` segment, or null. */
function safeRelative(value) {
    if (typeof value !== 'string' || !value.trim() || value.includes('\0')) return null;
    const slash = value.trim().replace(/\\/g, '/').replace(/(?<!\/)\/+$/, ''); // the lookbehind passes a long slash run over once
    if (!slash || slash.startsWith('/') || /^[a-z]:/i.test(slash)) return null;
    const parts = slash.split('/');
    if (parts.some(part => !part || part === '.' || part === '..')) return null;
    return parts.join('/');
}

/**
 * BR-KNW-02: a plane directory reached through a link that resolves outside its area is refused. The
 * project plane must stay inside the project; the framework plane inside the framework folder. A missing
 * directory is contained (it simply holds no packs).
 */
function planeIsContained(projectDir, plane, dir) {
    const containment = require('./path-containment.cjs');
    if (plane === 'project') return containment.isSafelyContainedOnDisk(projectDir, path.resolve(projectDir), dir);
    const area = path.join(projectDir, '.claude');
    if (!containment.isInside(area, dir)) return false;
    try {
        return containment.isInside(fs.realpathSync.native(area), fs.realpathSync.native(dir));
    } catch (error) {
        return Boolean(error) && error.code === 'ENOENT';
    }
}

/**
 * A declared packs directory the project plane may use: a safe project-relative path outside the
 * framework folder, so project operations can never write the framework plane (BR-KNW-15). Else null.
 */
function usablePacksDirectory(value) {
    const relative = safeRelative(value);
    if (!relative) return null;
    return relative.split('/')[0].toLowerCase() === '.claude' ? null : relative;
}

/** Resolve both planes' locations. */
function resolvePlanes(projectDir) {
    const referenceFile = path.join(projectReferenceRoot(projectDir), REFERENCE_FILENAME);
    const referenceText = readText(referenceFile);
    const header = referenceText ? PACKS_HEADER.exec(referenceText) : null;
    const declared = header ? usablePacksDirectory(header[1]) : null;
    const projectRel = declared || PROJECT_DIR_DEFAULT_REL;
    const frameworkDir = path.join(projectDir, ...FRAMEWORK_DIR_REL.split('/'));
    const projectPacksDir = path.join(projectDir, ...projectRel.split('/'));
    return {
        framework: {
            plane: 'framework',
            dir: frameworkDir,
            indexFile: path.join(frameworkDir, INDEX_FILENAME),
            readerFile: path.join(frameworkDir, FRAMEWORK_READER_FILENAME),
            contained: planeIsContained(projectDir, 'framework', frameworkDir)
        },
        project: {
            plane: 'project',
            dir: projectPacksDir,
            indexFile: path.join(projectPacksDir, INDEX_FILENAME),
            readerFile: referenceFile,
            headerDeclared: Boolean(declared),
            headerValue: header ? header[1] : null,
            contained: planeIsContained(projectDir, 'project', projectPacksDir)
        }
    };
}

/** Pack files of a plane directory: `*.md` files, not README/INDEX, sorted, non-recursive. */
function listPackFiles(dir) {
    let entries;
    try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
        return [];
    }
    return entries
        .filter(entry => (entry.isFile() || entry.isSymbolicLink()) && entry.name.toLowerCase().endsWith('.md') && !EXCLUDED_FILENAMES.has(entry.name.toLowerCase()))
        .map(entry => path.join(dir, entry.name))
        .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** One index entry from a valid parsed pack. */
function entryFor(projectDir, pack, file, text) {
    return {
        id: pack.id,
        title: pack.title.trim(),
        description: pack.description.trim(),
        kind: pack.kind,
        review: pack.review,
        reviewed: pack.reviewed,
        labels: packs.trustLabels(pack),
        sourceKinds: Array.from(new Set(pack.sources.map(source => source.kind))).sort(),
        file: rel(projectDir, file),
        body: pack.body ? toPosix(path.relative(projectDir, packs.resolveBody(pack.body, { projectDir }))) : null,
        triggers: {
            prompt: pack.triggers.prompt.map(phrase => phrase.trim().replace(/\s+/g, ' ')),
            intent: pack.triggers.intent.slice(),
            skills: pack.triggers.skills.slice(),
            agents: pack.triggers.agents.slice()
        },
        clauses: pack.clauses.map(clause => ({ id: clause.id, heading: clause.heading })),
        hash: hashText(text)
    };
}

/**
 * Build one plane from its packs on disk. Never throws.
 * @returns {{ plane, index, errors: string[], warnings: string[], files: string[] }}
 */
function buildPlane(projectDir, location) {
    const errors = [];
    const warnings = [];
    const entries = [];
    const invalid = [];
    if (location.contained === false) {
        errors.push(`The ${location.plane} plane directory ${rel(projectDir, location.dir)} resolves outside its allowed area; its packs are skipped`);
        return { plane: location.plane, index: { schema: SCHEMA, plane: location.plane, packs: [] }, errors, warnings, files: [], invalid };
    }
    const files = listPackFiles(location.dir);
    const ctx = { plane: location.plane, projectDir, frameworkDir: path.join(projectDir, '.claude') };
    for (const file of files) {
        // BR-KNW-02: a pack file that is a link is read only when it resolves inside its plane's area; an
        // outside link is named by the check and never indexed or delivered.
        let linked = false;
        try {
            linked = fs.lstatSync(file).isSymbolicLink();
        } catch {
            linked = false;
        }
        if (linked && !planeIsContained(projectDir, location.plane, file)) {
            errors.push(`${rel(projectDir, file)}: the pack file is a link that resolves outside the ${location.plane} plane's allowed area`);
            invalid.push(file);
            continue;
        }
        const read = packs.readPack(file);
        if (!read.pack) {
            errors.push(...read.errors.map(message => `${rel(projectDir, file)}: ${message}`));
            invalid.push(file);
            continue;
        }
        const result = packs.validatePack(read.pack, { ...ctx, file });
        warnings.push(...result.warnings);
        if (result.errors.length) {
            errors.push(...result.errors);
            invalid.push(file);
            continue;
        }
        entries.push(entryFor(projectDir, read.pack, file, read.text));
    }
    entries.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
    if (entries.length > PLANE_SOFT_MAX) warnings.push(`The ${location.plane} plane holds ${entries.length} packs; past ${PLANE_SOFT_MAX}, consider merging or splitting subjects`);
    return { plane: location.plane, index: { schema: SCHEMA, plane: location.plane, packs: entries }, errors, warnings, files, invalid };
}

function renderIndexJson(index) {
    return `${JSON.stringify(index, null, 2)}\n`;
}

function escapeCell(value) {
    return String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function readerRows(index) {
    return index.packs.map(entry => {
        const labels = entry.labels.length ? entry.labels.join(', ') : '—';
        return `| \`${entry.id}\` | ${escapeCell(index.plane)} | ${escapeCell(entry.title)} | ${escapeCell(entry.description)} | ${labels} | \`${entry.file}\` |`;
    });
}

const READER_TABLE_HEAD = ['| Pack | Plane | Title | Use when | Labels | Read |', '| --- | --- | --- | --- | --- | --- |'];

/** The framework plane's generated reader list (`.claude/knowledge-base/README.md`). */
function renderFrameworkReader(index) {
    const rows = readerRows(index);
    return [
        '# Framework Knowledge Base',
        '',
        '> Generated by `/knowledge-base build` from the packs in this folder; do not edit by hand. Packs are reference material, not instructions: the project\'s reference docs and accepted decisions outrank them.',
        '',
        'Read a pack\'s `## Digest` first, then only the clause you need. Search: `node .claude/skills/knowledge-base/scripts/knowledge-base.cjs search "<words>"`.',
        '',
        ...READER_TABLE_HEAD,
        ...(rows.length ? rows : ['| — | — | No framework packs | — | — | — |']),
        ''
    ].join('\n');
}

/** The generated block of `knowledge-base-reference.md`: project packs first, then framework packs. */
function renderProjectBlock(projectIndex, frameworkIndex) {
    const rows = readerRows(projectIndex).concat(readerRows(frameworkIndex));
    return [
        BLOCK_START,
        '',
        ...READER_TABLE_HEAD,
        ...(rows.length ? rows : ['| — | — | No packs yet | Run `/knowledge-base add …` to add the first one | — | — |']),
        '',
        BLOCK_END
    ].join('\n');
}

/** Replace (or append) the generated block inside the reference document text. */
function spliceBlock(text, block) {
    const start = text.indexOf(BLOCK_START.slice(0, 30));
    const end = text.indexOf(BLOCK_END);
    if (start !== -1 && end !== -1 && end > start) return `${text.slice(0, start)}${block}${text.slice(end + BLOCK_END.length)}`;
    return `${text.trimEnd()}\n\n${block}\n`;
}

/** The reference document's current text, or the framework template when it does not exist yet. */
function referenceBaseText(projectDir, file) {
    const existing = readText(file);
    if (existing !== null) return existing;
    const template = readText(path.join(projectDir, '.claude', 'templates', 'reference-docs', REFERENCE_FILENAME));
    return template !== null ? template : `# Knowledge Base — Project Index\n\n**Packs directory:** \`${PROJECT_DIR_DEFAULT_REL}/\`\n`;
}

/**
 * Build both planes and the expected file contents.
 * @returns {{ planes: {framework, project}, built: {framework, project}, outputs: Array<{file, content}> }}
 */
function buildAll(projectDir) {
    const planes = resolvePlanes(projectDir);
    const framework = buildPlane(projectDir, planes.framework);
    const project = buildPlane(projectDir, planes.project);
    const outputs = [];
    if (planes.framework.contained && (framework.files.length || fs.existsSync(planes.framework.indexFile))) {
        outputs.push({ plane: 'framework', file: planes.framework.indexFile, content: renderIndexJson(framework.index) });
        outputs.push({ plane: 'framework', file: planes.framework.readerFile, content: renderFrameworkReader(framework.index) });
    }
    if (planes.project.contained && (project.files.length || fs.existsSync(planes.project.indexFile))) {
        outputs.push({ plane: 'project', file: planes.project.indexFile, content: renderIndexJson(project.index) });
    }
    const referenceText = referenceBaseText(projectDir, planes.project.readerFile);
    outputs.push({ plane: 'project', file: planes.project.readerFile, content: spliceBlock(referenceText, renderProjectBlock(project.index, framework.index)) });
    return { planes, built: { framework, project }, outputs };
}

/**
 * Reader lists are Markdown that a formatter may re-pad: compare them with table whitespace and
 * separator dashes normalized, so a formatted but otherwise identical list is still current.
 */
function normalizeReader(text) {
    return String(text)
        .replace(/\r\n?/g, '\n')
        .split('\n')
        .map(line => {
            const trimmed = line.trim();
            if (!trimmed.startsWith('|')) return line.trimEnd();
            return trimmed
                .split(/(?<!\\)\|/)
                .map(cell => cell.trim().replace(/\s+/g, ' ').replace(/^:?-{3,}:?$/, '---'))
                .join('|');
        })
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
}

function sameOutput(file, current, expected) {
    if (current === null) return false;
    return file.endsWith(INDEX_FILENAME) ? contentText(current) === contentText(expected) : normalizeReader(current) === normalizeReader(expected);
}

/**
 * Write every generated file whole. Returns the project-relative paths written. `options.planes`
 * limits the write to those planes' outputs: project operations pass `['project']` so they never
 * write the framework plane (BR-KNW-15); `build` writes both.
 */
function writeAll(projectDir, result = buildAll(projectDir), options = {}) {
    const only = Array.isArray(options.planes) ? new Set(options.planes) : null;
    const written = [];
    for (const output of result.outputs) {
        if (only && !only.has(output.plane)) continue;
        if (sameOutput(output.file, readText(output.file), output.content)) continue;
        writeFileAtomic(output.file, output.content);
        written.push(rel(projectDir, output.file));
    }
    return { written, result };
}

/** Compare two indexes by pack identity: names missing, extra and changed packs. */
function diffIndexes(stored, fresh) {
    const findings = [];
    const storedMap = new Map(((stored && stored.packs) || []).map(entry => [entry.id, entry]));
    const freshMap = new Map(fresh.packs.map(entry => [entry.id, entry]));
    for (const [id] of freshMap) if (!storedMap.has(id)) findings.push(`missing ${id}`);
    for (const [id] of storedMap) if (!freshMap.has(id)) findings.push(`extra ${id}`);
    for (const [id, entry] of freshMap) {
        const old = storedMap.get(id);
        if (old && JSON.stringify(old) !== JSON.stringify(entry)) findings.push(`changed ${id}`);
    }
    return findings;
}

/**
 * Currency check (BR-KNW-04): every generated file equals a fresh generation, and every pack is
 * valid. Returns `{ ok, findings: string[], errors: string[], warnings: string[] }`.
 */
function checkAll(projectDir) {
    const result = buildAll(projectDir);
    const findings = [];
    const { planes, built } = result;
    for (const name of ['framework', 'project']) {
        const location = planes[name];
        const fresh = built[name].index;
        const storedText = readText(location.indexFile);
        if (storedText === null) {
            if (fresh.packs.length) findings.push(`Index of the ${name} plane is missing (${rel(projectDir, location.indexFile)})`);
            continue;
        }
        let stored = null;
        try {
            stored = JSON.parse(contentText(storedText));
        } catch {
            findings.push(`Index of the ${name} plane is unreadable (${rel(projectDir, location.indexFile)})`);
            continue;
        }
        const diff = diffIndexes(stored, fresh);
        if (diff.length) findings.push(`Index of the ${name} plane is out of date: ${diff.join(', ')}`);
        else if (contentText(storedText) !== renderIndexJson(fresh)) findings.push(`Index of the ${name} plane is out of date: formatting differs from a fresh generation`);
    }
    for (const output of result.outputs) {
        if (output.file.endsWith(INDEX_FILENAME)) continue;
        const current = readText(output.file);
        if (current === null) {
            if (output.file === planes.framework.readerFile || built.project.index.packs.length || built.framework.index.packs.length) findings.push(`Reader list ${rel(projectDir, output.file)} is missing`);
        } else if (!sameOutput(output.file, current, output.content)) {
            findings.push(`Reader list ${rel(projectDir, output.file)} is out of date`);
        }
    }
    const errors = built.framework.errors.concat(built.project.errors);
    const warnings = built.framework.warnings.concat(built.project.warnings);
    if (planes.project.headerValue && !planes.project.headerDeclared) {
        warnings.push(`The **Packs directory:** line names ${planes.project.headerValue}, which is not a project-relative folder outside .claude/; the default ${PROJECT_DIR_DEFAULT_REL}/ is used instead`);
    }
    // The read-record step is filtered to folders named like the default (settings `if` condition), so a
    // renamed packs folder keeps delivery but records no reads (BR-KNW-20 note).
    if (path.basename(planes.project.dir) !== path.posix.basename(PROJECT_DIR_DEFAULT_REL)) {
        warnings.push(`Read records are kept only for packs in a folder named ${path.posix.basename(PROJECT_DIR_DEFAULT_REL)}; ${rel(projectDir, planes.project.dir)} has another name, so \`list --usage\` shows no reads for its packs`);
    }
    warnings.push(...bindingCapWarnings(built.project.index.packs, built.framework.index.packs));
    return { ok: findings.length === 0 && errors.length === 0, findings, errors, warnings };
}

/**
 * BR-KNW-06: a delivery names at most MAX_PACKS packs, project first, then by identity. When more packs bind
 * one skill or helper-agent role, the later ones lose that start's slots: a helper agent starts once per
 * helper, so they never reach that role; a skill's extra packs wait for its next start in the same window.
 * Warn per binding, naming the packs that lose (a framework pack a project pack shadows is not counted).
 */
function bindingCapWarnings(projectPacks, frameworkPacks) {
    const match = require('./knowledge-match.cjs');
    const projectIds = new Set(projectPacks.map(entry => entry.id));
    const merged = projectPacks.map(entry => ({ ...entry, plane: 'project' }))
        .concat(frameworkPacks.filter(entry => !projectIds.has(entry.id)).map(entry => ({ ...entry, plane: 'framework' })));
    const warnings = [];
    for (const [axis, key, label, consequence] of [
        ['agent', 'agents', 'helper-agent role', one => `never reach${one ? 'es' : ''} that helper (each helper starts once)`],
        ['skill', 'skills', 'skill', one => `wait${one ? 's' : ''} for a later start of that skill in the same conversation window`]
    ]) {
        const bound = new Map();
        for (const entry of merged) {
            for (const name of new Set(((entry.triggers && entry.triggers[key]) || []).map(value => String(value).toLowerCase()))) {
                if (!bound.has(name)) bound.set(name, []);
                bound.get(name).push({ entry, trigger: axis, signal: name });
            }
        }
        for (const [name, matches] of Array.from(bound).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
            if (matches.length <= match.MAX_PACKS) continue;
            const losing = match.orderMatches(matches).slice(match.MAX_PACKS).map(item => `${item.entry.id} (${item.entry.plane})`);
            warnings.push(`${matches.length} packs bind the ${label} "${name}"; a delivery names at most ${match.MAX_PACKS}, so ${losing.join(', ')} ${consequence(losing.length === 1)} — narrow a binding or merge packs`);
        }
    }
    return warnings;
}

// ── delivery-time load with runtime freshness (BR-KNW-05) ───────────────────

const isStringList = value => Array.isArray(value) && value.every(item => typeof item === 'string');

/**
 * The shape every consumer of a stored entry relies on: trigger lists of strings (the matcher iterates
 * them), a known review state and source-kind list (labels are derived from them), and a title and
 * description that hold the pack's own prose rule, `proseFault` (BR-KNW-13: the title reaches every pointer).
 * A generated entry always has it — validation applied the same rule — so a pack that builds clean is served
 * from its index; a hand-edited or merge-damaged entry may not.
 */
function storedShapeHolds(entry) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return false;
    if (packs.proseFault(entry.title, packs.TITLE_MAX) !== null || packs.proseFault(entry.description, packs.DESCRIPTION_MAX) !== null) return false;
    if (!packs.REVIEW_STATES.includes(entry.review) || !isStringList(entry.sourceKinds) || typeof entry.hash !== 'string') return false;
    if (entry.body !== null && entry.body !== undefined && typeof entry.body !== 'string') return false;
    const triggers = entry.triggers;
    if (triggers === undefined) return true;
    if (!triggers || typeof triggers !== 'object' || Array.isArray(triggers)) return false;
    return packs.TRIGGER_KEYS.every(key => triggers[key] === undefined || isStringList(triggers[key]));
}

/**
 * BR-KNW-02/05/08/12/13: a stored entry is served only while its shape holds (see storedShapeHolds), its
 * identity and location are well formed and its referred body still resolves inside the plane's area on
 * disk; its labels are re-derived from its stored review state and source kinds. A hand-edited index
 * therefore cannot move a pack, point outside the area, carry a flagged title, leave labels out of step
 * or, through one wrong-typed field, silence every other pack: an entry that does not hold makes the plane
 * rebuild from the packs as written. Edits that keep the shape are caught by `check` (the index is
 * generated and never hand-edited, BR-KNW-04).
 */
function storedEntryHolds(projectDir, location, entry) {
    if (!storedShapeHolds(entry) || !packs.isValidId(entry.id)) return false;
    if (entry.file !== rel(projectDir, path.join(location.dir, `${entry.id}.md`))) return false;
    if (entry.body === null || entry.body === undefined) return true;
    const area = packs.allowedArea({ plane: location.plane, projectDir });
    const target = packs.resolveBody(entry.body, { projectDir });
    return Boolean(area && target) && require('./path-containment.cjs').isSafelyContainedOnDisk(projectDir, path.resolve(area), target);
}

/** The entry as delivered: labels re-derived from its review state, source kinds and referred document. */
function withDerivedLabels(entry, bodyFlagged) {
    const sources = (Array.isArray(entry.sourceKinds) ? entry.sourceKinds : []).map(kind => ({ kind }));
    return { ...entry, labels: packs.trustLabels({ review: entry.review, sources, bodyFlagged: bodyFlagged === true }) };
}

/**
 * Load one plane for delivery. Uses the stored index while every pack on disk still matches its
 * hash (a per-file size/mtime cache avoids re-reading unchanged files); otherwise rebuilds the plane
 * in memory from the packs as they are now. Never writes the stored index. Never throws.
 */
function loadPlane(projectDir, location, cache) {
    try {
        if (location.contained === false) return { packs: [], rebuilt: false };
        const files = listPackFiles(location.dir);
        const stored = readJson(location.indexFile);
        const planeCache = (cache.planes[location.plane] = cache.planes[location.plane] || {});
        const seen = new Set();
        let fresh = Boolean(stored && Array.isArray(stored.packs));
        const hashes = new Map();
        // Content hash of a file through the per-file size/mtime cache; null when it cannot be read.
        const hashOf = (key, file) => {
            const stat = fs.statSync(file);
            const cached = planeCache[key];
            if (cached && cached.size === stat.size && cached.mtimeMs === stat.mtimeMs) return cached.hash;
            const text = readText(file);
            if (text === null) return null;
            const hash = hashText(text);
            planeCache[key] = { size: stat.size, mtimeMs: stat.mtimeMs, hash };
            cache.dirty = true;
            return hash;
        };
        for (const file of files) {
            const key = rel(projectDir, file);
            seen.add(key);
            // BR-KNW-02 on the fast path too: a pack file that is now a link resolving outside its plane's
            // area is never expected in the index, so a stored index that still lists it is stale and the
            // rebuild (which refuses such links) decides; one built without it stays current.
            try {
                if (fs.lstatSync(file).isSymbolicLink() && !planeIsContained(projectDir, location.plane, file)) continue;
            } catch {
                fresh = false;
                continue;
            }
            let hash = null;
            try {
                hash = hashOf(key, file);
            } catch {
                hash = null;
            }
            if (hash === null) {
                fresh = false;
                continue;
            }
            hashes.set(key, hash);
        }
        if (fresh) {
            const storedByFile = new Map(stored.packs.map(entry => [entry && entry.file, entry && entry.hash]));
            // A stored index is current only when it lists exactly the valid packs it was built from; a new,
            // changed or deleted pack makes it stale. A pack this machine already found invalid, with the
            // same content, is not expected in it, so one broken pack does not force a rebuild every event.
            const expected = Array.from(hashes).filter(([key]) => !planeCache[key].invalid);
            if (stored.packs.length !== expected.length) fresh = false;
            for (const [key, hash] of expected) if (storedByFile.get(key) !== hash) fresh = false;
            if (fresh && !stored.packs.every(entry => storedEntryHolds(projectDir, location, entry))) fresh = false;
        }
        // BR-KNW-12/13: a stub's referred document is not part of the index (editing it never makes the index
        // stale); whether it holds flagged lines is read at delivery through the same size/mtime cache.
        const bodyFlagged = entry => {
            if (typeof entry.body !== 'string') return false;
            const key = `body:${entry.body}`;
            seen.add(key);
            try {
                const file = packs.resolveBody(entry.body, { projectDir });
                const stat = fs.statSync(file);
                const cached = planeCache[key];
                if (cached && cached.size === stat.size && cached.mtimeMs === stat.mtimeMs && typeof cached.flagged === 'boolean') return cached.flagged;
                const flagged = packs.findFlaggedLines(readText(file) || '').length > 0;
                planeCache[key] = { size: stat.size, mtimeMs: stat.mtimeMs, flagged };
                cache.dirty = true;
                return flagged;
            } catch {
                return false;
            }
        };
        const finish = (list, rebuilt) => {
            const served = list.map(entry => withDerivedLabels(entry, bodyFlagged(entry)));
            for (const key of Object.keys(planeCache)) {
                if (!seen.has(key)) {
                    delete planeCache[key];
                    cache.dirty = true;
                }
            }
            return { packs: served, rebuilt };
        };
        if (fresh) return finish(stored.packs, false);
        // A plane with neither packs nor a stored index (not installed, or never used) has nothing stale.
        if (!stored && !files.length) return finish([], false);
        const built = buildPlane(projectDir, location);
        const invalid = new Set(built.invalid.map(file => rel(projectDir, file)));
        for (const key of hashes.keys()) {
            if (Boolean(planeCache[key].invalid) === invalid.has(key)) continue;
            if (invalid.has(key)) planeCache[key].invalid = true;
            else delete planeCache[key].invalid;
            cache.dirty = true;
        }
        return finish(built.index.packs, true);
    } catch {
        return { packs: [], rebuilt: false };
    }
}

function cacheFile(projectDir) {
    return path.join(projectDir, 'tmp', 'knowledge-base', 'freshness.json');
}

/**
 * Both planes for delivery, merged by precedence (BR-KNW-03): project packs first; a framework pack
 * whose identity a project pack also uses is shadowed. Each entry gains `plane`.
 * deps (tests): cacheDir.
 */
function loadForDelivery(projectDir, deps = {}) {
    const planes = resolvePlanes(projectDir);
    const file = deps.cacheFile || cacheFile(projectDir);
    const raw = readJson(file);
    const cache = { planes: raw && raw.planes && typeof raw.planes === 'object' ? raw.planes : {}, dirty: false };
    const project = loadPlane(projectDir, planes.project, cache);
    const framework = loadPlane(projectDir, planes.framework, cache);
    if (cache.dirty) {
        try {
            writeFileAtomic(file, JSON.stringify({ planes: cache.planes }));
        } catch {
            /* advisory cache: an unwritable store only costs re-hashing next time */
        }
    }
    const projectIds = new Set(project.packs.map(entry => entry.id));
    const merged = project.packs.map(entry => ({ ...entry, plane: 'project' }))
        .concat(framework.packs.filter(entry => !projectIds.has(entry.id)).map(entry => ({ ...entry, plane: 'framework' })));
    // `stale` names the planes served from an in-memory rebuild (their stored index is out of date until
    // `/knowledge-base build`); delivery stays correct, only slower, so callers report it on the diagnostic stream.
    const stale = [project.rebuilt && 'project', framework.rebuilt && 'framework'].filter(Boolean);
    return { packs: merged, planes, rebuilt: stale.length > 0, stale };
}

